const { chromium } = require('playwright');
const [,, url, out, w='390', h='844', lang='ar'] = process.argv;
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=swiftshader','--enable-webgl','--ignore-gpu-blocklist'] });
  const p = await b.newPage({ viewport: { width: +w, height: +h }, isMobile: +w < 600, hasTouch: +w < 600 });
  const errs = [];
  p.on('pageerror', e => errs.push('pageerror: ' + e.message));
  p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await p.addInitScript((l) => { try { localStorage.clear(); localStorage.setItem('rihla_lang', JSON.stringify(l)); } catch(e){} }, lang);
  await p.goto(url, { waitUntil: 'networkidle' });
  await p.waitForTimeout(2500);
  const shot = async (n) => p.screenshot({ path: `${out}-${n}.jpg`, quality: 55, type: 'jpeg' });
  for (const id of ['hero','s2','s4','s5']) { await p.evaluate((id)=>document.getElementById(id).scrollIntoView({block:'start'}), id); await p.waitForTimeout(2200); await shot(id); }
  await p.evaluate(()=>document.getElementById('start').scrollIntoView()); await p.waitForTimeout(1500);
  const click = async (sel) => { await p.click(sel); await p.waitForTimeout(250); };
  // step 0: try next without answers → error
  await click('[data-next]');
  const err0 = await p.textContent('#ferr');
  await click('[data-field="who"][data-id="parent"]'); await click('[data-field="stage"][data-id="g12"]');
  await shot('f0'); await click('[data-next]');
  await click('[data-field="grades"][data-id="80_89"]'); await click('[data-field="english"][data-id="good"]');
  const deg = await p.getAttribute('[data-field="degree"][data-id="bachelor"]', 'aria-pressed');
  await shot('f1'); await click('[data-next]');
  await click('[data-group="eng"]'); await click('[data-field="majors"][data-id="eng_mech"]'); await click('[data-field="majors"][data-id="eng_mecha"]');
  await click('[data-group="it"]'); await click('[data-field="majors"][data-id="it_cyber"]');
  await shot('f2'); await click('[data-next]');
  await click('[data-field="uniTarget"][data-id="yes"]');
  await p.fill('#unisearch', 'utm'); await p.waitForTimeout(200);
  const visible = await p.$$eval('[data-search]', els => els.filter(e => !e.hidden).length);
  await p.fill('#unisearch', ''); await p.dispatchEvent('#unisearch','input');
  await click('[data-field="unis"][data-id="utm"]'); await click('[data-field="unis"][data-id="monash"]');
  await shot('f3'); await click('[data-next]');
  await click('[data-field="budget"][data-id="20_35"]'); await click('[data-field="intake"][data-id="2027_09"]'); await click('[data-field="recognition"][data-id="yes"]'); await click('[data-field="funding"][data-id="self"]');
  await click('[data-next]');
  await p.fill('input[name="name"]', lang==='ar'?'محمد العتيبي':'Mohammed Alotaibi');
  await p.fill('input[name="studentName"]', lang==='ar'?'سارة':'Sara');
  await p.fill('input[name="phone"]', '0512345678');
  await p.fill('input[name="email"]', 'test@example.com');
  await click('[data-field="city"][data-id="riyadh"]'); await click('[data-field="mode"][data-id="online"]'); await click('[data-field="time"][data-id="evening"]');
  await click('[data-next]');
  const err5 = await p.textContent('#ferr');
  await p.check('input[name="consent"]');
  await shot('f5');
  await click('[data-next]'); await p.waitForTimeout(1200);
  const ok = await p.isVisible('.success');
  await p.evaluate(()=>document.querySelector('.formcard').scrollIntoView()); await p.waitForTimeout(500);
  await shot('ok');
  const wa = await p.getAttribute('.success a[href*="wa.me"]', 'href');
  console.log(JSON.stringify({ err0, deg, visible, err5, ok, wa: decodeURIComponent(wa||'').slice(0,220), errs }, null, 1));
  await b.close();
})();
